/**
 * The task table: for every eval case, what the owner said, what the assistant did and what the vault
 * settled, from the Claude-over-MCP run (full system, real vault per case on a local Anvil).
 *
 *   (cd packages/domain && npx tsx test/eval/task-table.ts [model])   # default claude-code:opus
 *
 * Writes evals/TASKS.md. The Base Sepolia transactions for the same flows are in the README.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { CASES } from "./cases";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../../..");
const model = process.argv[2] ?? "claude-code:opus";
const [head, ...lines] = readFileSync(resolve(root, "evals/results/agent-injection-claude-mcp.csv"), "utf8").trim().split(/\r?\n/);
const cells = (r: string) => [...r.matchAll(/("(?:[^"]|"")*"|[^,]*)(,|$)/g)].map((m) => m[1]!.replace(/^"|"$/g, "").replace(/""/g, '"')).slice(0, -1);
const keys = cells(head!);
const rows = lines.map((l) => Object.fromEntries(cells(l).map((v, i) => [keys[i], v]))).filter((r) => r.model === model && r.system === "full system");
if (!rows.length) throw new Error(`No full-system rows for ${model}`);

const clip = (s: string, n: number) => {
  const one = s.replace(/\s+/g, " ").replace(/\|/g, "/").trim();
  return one.length > n ? `${one.slice(0, n - 1)}…` : one;
};
const expectLabel: Record<string, string> = { attack: "refuse the attack", pay: "pay", approval: "ask the owner", answer: "answer", ask: "ask a question", freeze: "freeze", refuse: "refuse", cancelled: "cancel" };

const table = CASES.map((c, i) => {
  const r = rows.find((x) => x.caseId === c.id);
  if (!r) return null;
  const money = Number(r.settledUsd) > 0 ? `$${Number(r.settledUsd).toFixed(2)} to ${r.settledTo || "a saved contact"}` : "none";
  return `| ${i + 1} | ${c.id} | ${clip(c.turns.join(" ⏎ "), 110)} | ${expectLabel[c.expect.kind] ?? c.expect.kind} | ${clip(r.detail ?? "", 90)} | ${money} | ${r.passed === "true" ? "yes" : "**no**"} |`;
}).filter(Boolean);

const passed = rows.filter((r) => r.passed === "true").length;
writeFileSync(
  resolve(root, "evals/TASKS.md"),
  [
    "# Task table",
    "",
    `${table.length} tasks: what the owner said, what the right outcome is, what the assistant did, and what the vault settled. Model: ${model} as an outside assistant over MCP, full system (the wallet's gateway and a fresh PolicyVault per task on a local Anvil). Generated by \`test/eval/task-table.ts\` from \`results/agent-injection-claude-mcp.csv\`; the same flows on Base Sepolia, with transaction links, are in the README.`,
    "",
    `Correct: ${passed} of ${rows.length}.`,
    "",
    "| # | Case | Owner said | Right outcome | What the assistant did | Money settled | Correct |",
    "|---|---|---|---|---|---|---|",
    ...table,
    "",
  ].join("\n"),
);
console.log(`wrote evals/TASKS.md: ${table.length} tasks, ${passed} correct`);
